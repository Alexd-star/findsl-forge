from __future__ import annotations

import argparse
import hashlib
import shutil
import subprocess
import sys
import tempfile
import urllib.request
from pathlib import Path


VERSION = "4.13.2"
JAR_NAME = f"antlr-{VERSION}-complete.jar"
JAR_URL = f"https://www.antlr.org/download/{JAR_NAME}"
ROOT = Path(__file__).resolve().parents[1]
GRAMMAR = ROOT / "grammar" / "OfficialSlot.g4"
CHECKSUM_FILE = ROOT / "tools" / "antlr" / f"{JAR_NAME}.sha256"
CACHE_JAR = Path.home() / ".cache" / "findsl-forge" / "antlr" / JAR_NAME
OUTPUT = ROOT / "src" / "findsl" / "official" / "frontend" / "generated"


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _expected_checksum() -> str:
    return CHECKSUM_FILE.read_text(encoding="ascii").split()[0].lower()


def _ensure_jar() -> Path:
    expected = _expected_checksum()
    if CACHE_JAR.exists() and _sha256(CACHE_JAR) == expected:
        return CACHE_JAR
    CACHE_JAR.parent.mkdir(parents=True, exist_ok=True)
    with urllib.request.urlopen(JAR_URL, timeout=60) as response, CACHE_JAR.open("wb") as target:
        shutil.copyfileobj(response, target)
    actual = _sha256(CACHE_JAR)
    if actual != expected:
        CACHE_JAR.unlink(missing_ok=True)
        raise RuntimeError(f"ANTLR jar checksum mismatch: expected {expected}, got {actual}")
    return CACHE_JAR


def _generate(destination: Path) -> None:
    destination.mkdir(parents=True, exist_ok=True)
    subprocess.run(
        [
            "java",
            "-jar",
            str(_ensure_jar()),
            "-Dlanguage=Python3",
            "-visitor",
            "-no-listener",
            "-Xexact-output-dir",
            "-o",
            str(destination),
            str(GRAMMAR),
        ],
        cwd=ROOT,
        check=True,
    )
    (destination / "__init__.py").write_text(
        '"""Generated by ANTLR 4.13.2; do not edit manually."""\n',
        encoding="ascii",
    )


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate the pinned official DSL ANTLR frontend")
    parser.add_argument("--check", action="store_true", help="Fail when committed sources differ from regeneration")
    args = parser.parse_args()
    if not args.check:
        _generate(OUTPUT)
        return 0
    with tempfile.TemporaryDirectory(prefix="findsl-antlr-") as directory:
        candidate = Path(directory) / "generated"
        _generate(candidate)
        committed = {p.name: p.read_bytes() for p in OUTPUT.iterdir() if p.is_file()}
        regenerated = {p.name: p.read_bytes() for p in candidate.iterdir() if p.is_file()}
        if committed != regenerated:
            print("Generated ANTLR sources are stale; run python scripts/generate_antlr.py", file=sys.stderr)
            return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
