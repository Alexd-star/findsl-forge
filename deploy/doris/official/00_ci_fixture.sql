CREATE DATABASE IF NOT EXISTS newzl;

CREATE TABLE IF NOT EXISTS newzl.hsj_stock_hq_basic (
  mktcode INTEGER NOT NULL,
  tgtcode VARCHAR(16) NOT NULL,
  bizdate DATE NOT NULL,
  volume BIGINT,
  turnover BIGINT
)
UNIQUE KEY(mktcode, tgtcode, bizdate)
DISTRIBUTED BY HASH(mktcode, tgtcode) BUCKETS 4
PROPERTIES (
  "replication_num" = "1",
  "enable_unique_key_merge_on_write" = "true"
);

