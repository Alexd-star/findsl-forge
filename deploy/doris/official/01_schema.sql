  hyBlkRefName VARCHAR(32),
  stFlag BOOLEAN NOT NULL DEFAULT FALSE,
  ahFlag BOOLEAN NOT NULL DEFAULT FALSE,
  hkConnFlag BOOLEAN NOT NULL DEFAULT FALSE,
  shConnFlag BOOLEAN NOT NULL DEFAULT FALSE,
  szConnFlag BOOLEAN NOT NULL DEFAULT FALSE,
  hsFlag BOOLEAN NOT NULL DEFAULT FALSE,
  hsjFlag BOOLEAN NOT NULL DEFAULT FALSE,
  kcbFlag BOOLEAN NOT NULL DEFAULT FALSE,
  gemFlag BOOLEAN NOT NULL DEFAULT FALSE,
  bShareFlag BOOLEAN NOT NULL DEFAULT FALSE
)
UNIQUE KEY(mktcode, tgtcode)
DISTRIBUTED BY HASH(mktcode, tgtcode) BUCKETS 16
PROPERTIES (
  "replication_num" = "1",
  "compression" = "LZ4",
  "enable_unique_key_merge_on_write" = "true"
);

