from __future__ import annotations

import csv
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, Iterable, List, Tuple

from .compiler import Compiler
from .registry import Registry, default_registry


@dataclass(frozen=True)
class DorisAssets:
    schema_sql: str
    sample_data_sql: str
    prefix_sql: str
    smoke_sql: str

    def files(self) -> Dict[str, str]:
        return {
            "01_schema.sql": self.schema_sql,
            "02_sample_data.sql": self.sample_data_sql,
            "03_build_prefix_tables.sql": self.prefix_sql,
            "04_smoke_queries.sql": self.smoke_sql,
        }


BASE_TABLES = ["daily_quote", "money_flow", "stock_universe"]
SMOKE_DSL = 'filter(SUM(indicator("volume"), 3) > 300)'
DEFAULT_COLOCATE_GROUP = "findsl_stock_by_ts"
DEFAULT_PARTITION_GRANULARITY = "month"


def render_doris_assets(
    data_dir: Path,
    registry: Registry = None,
    database: str = "findsl_demo",
    buckets: int = 8,
    replication_num: int = 1,
    colocate_group: str = DEFAULT_COLOCATE_GROUP,
    partition_granularity: str = DEFAULT_PARTITION_GRANULARITY,
) -> DorisAssets:
    registry = registry or default_registry()
    data_dir = Path(data_dir)
    partition_granularity = _validate_partition_granularity(partition_granularity)
    return DorisAssets(
        schema_sql=_render_schema(
            registry,
            database,
            buckets,
            replication_num,
            colocate_group,
            partition_granularity,
        ),
        sample_data_sql=_render_sample_data(registry, data_dir, database),
        prefix_sql=_render_prefix_build(registry, database),
        smoke_sql=_render_smoke_queries(registry, database),
    )


def write_doris_assets(
    output_dir: Path,
    data_dir: Path,
    registry: Registry = None,
    database: str = "findsl_demo",
    buckets: int = 8,
    replication_num: int = 1,
    colocate_group: str = DEFAULT_COLOCATE_GROUP,
    partition_granularity: str = DEFAULT_PARTITION_GRANULARITY,
) -> DorisAssets:
    assets = render_doris_assets(
        data_dir=data_dir,
        registry=registry,
        database=database,
        buckets=buckets,
        replication_num=replication_num,
        colocate_group=colocate_group,
        partition_granularity=partition_granularity,
    )
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    for filename, content in assets.files().items():
        (output_dir / filename).write_text(content, encoding="utf-8")
    return assets


def _render_schema(
    registry: Registry,
    database: str,
    buckets: int,
    replication_num: int,
    colocate_group: str,
    partition_granularity: str,
) -> str:
    sections = [
        "-- Generated by FinDSL Forge. Review buckets, replication, and partition retention for production clusters.",
        f"CREATE DATABASE IF NOT EXISTS `{database}`;",
        f"USE `{database}`;",
        "",
    ]
    for table_name in BASE_TABLES:
        sections.append(
            _create_base_table_sql(
                registry,
                table_name,
                buckets,
                replication_num,
                colocate_group,
                partition_granularity,
            )
        )
        sections.append("")
    for prefix_table_name in _prefix_table_names(registry):
        sections.append(
            _create_prefix_table_sql(
                registry,
                prefix_table_name,
                buckets,
                replication_num,
                colocate_group,
                partition_granularity,
            )
        )
        sections.append("")
    return "\n".join(sections).rstrip() + "\n"


def _create_base_table_sql(
    registry: Registry,
    table_name: str,
    buckets: int,
    replication_num: int,
    colocate_group: str,
    partition_granularity: str,
) -> str:
    meta = registry.table(table_name)
    columns = _base_columns(registry, table_name)
    column_sql = ",\n  ".join(f"`{name}` {dtype}" for name, dtype in columns)
    code_column = meta.get("code_column", "ts_code")
    partition_column = meta.get("partition_column", "trade_date")
    return (
        f"CREATE TABLE IF NOT EXISTS `{meta['physical']}` (\n"
        f"  {column_sql}\n"
        f")\n"
        f"DUPLICATE KEY(`{code_column}`, `{partition_column}`)\n"
        + _auto_partition_sql(partition_column, partition_granularity)
        + "\n"
        f"DISTRIBUTED BY HASH(`{code_column}`) BUCKETS {buckets}\n"
        + _table_properties_sql(replication_num, colocate_group)
    )


def _create_prefix_table_sql(
    registry: Registry,
    prefix_table_name: str,
    buckets: int,
    replication_num: int,
    colocate_group: str,
    partition_granularity: str,
) -> str:
    meta = registry.table(prefix_table_name)
    columns = _prefix_columns(registry, prefix_table_name)
    column_sql = ",\n  ".join(f"`{name}` {dtype}" for name, dtype in columns)
    code_column = meta.get("code_column", "ts_code")
    partition_column = meta.get("partition_column", "trade_date")
    row_column = meta.get("row_column", "row_no")
    return (
        f"CREATE TABLE IF NOT EXISTS `{meta['physical']}` (\n"
        f"  {column_sql}\n"
        f")\n"
        f"DUPLICATE KEY(`{code_column}`, `{partition_column}`, `{row_column}`)\n"
        + _auto_partition_sql(partition_column, partition_granularity)
        + "\n"
        f"DISTRIBUTED BY HASH(`{code_column}`) BUCKETS {buckets}\n"
        + _table_properties_sql(replication_num, colocate_group)
    )


def _auto_partition_sql(partition_column: str, partition_granularity: str) -> str:
    return (
        f"AUTO PARTITION BY RANGE (date_trunc(`{partition_column}`, '{partition_granularity}'))\n"
        "()"
    )


def _table_properties_sql(replication_num: int, colocate_group: str) -> str:
    properties = [f'"replication_num" = "{replication_num}"']
    if colocate_group:
        properties.append(f'"colocate_with" = "{colocate_group}"')
    body = ",\n  ".join(properties)
    return f"PROPERTIES (\n  {body}\n);"


def _validate_partition_granularity(value: str) -> str:
    allowed = {"day", "week", "month", "year"}
    if value not in allowed:
        expected = ", ".join(sorted(allowed))
        raise ValueError(f"Unsupported Doris auto-partition granularity {value!r}; expected one of {expected}")
    return value


def _render_sample_data(registry: Registry, data_dir: Path, database: str) -> str:
    sections = [
        "-- Small fixture data for smoke tests. Use Stream Load for production-scale CSV import.",
        f"USE `{database}`;",
        "",
    ]
    for table_name in BASE_TABLES:
        rows = _read_csv(data_dir / f"{table_name}.csv")
        if not rows:
            continue
        physical = registry.table(table_name)["physical"]
        columns = list(rows[0].keys())
        sections.append(_insert_sql(physical, columns, rows))
        sections.append("")
    return "\n".join(sections).rstrip() + "\n"


def _render_prefix_build(registry: Registry, database: str) -> str:
    sections = [
        "-- Rebuild prefix tables after loading base tables.",
        f"USE `{database}`;",
        "",
    ]
    for prefix_table_name in _prefix_table_names(registry):
        source_table, indicators = _prefix_source(registry, prefix_table_name)
        prefix_physical = registry.table(prefix_table_name)["physical"]
        source_physical = registry.table(source_table)["physical"]
        select_columns, from_sql, ts_expr, date_expr, value_alias = _prefix_build_context(
            registry,
            source_table,
            source_physical,
        )
        for indicator_name, meta in indicators:
            value_expr = (
                f"{value_alias}.`{meta['column']}`"
                if value_alias
                else f"`{meta['column']}`"
            )
            select_columns.append(
                "SUM("
                + value_expr
                + f") OVER (PARTITION BY {ts_expr} ORDER BY {date_expr} "
                + "ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) AS `"
                + meta["prefix_column"]
                + "`"
            )
        sections.extend(
            [
                f"TRUNCATE TABLE `{prefix_physical}`;",
                f"INSERT INTO `{prefix_physical}`",
                "SELECT",
                "  " + ",\n  ".join(select_columns),
                from_sql + ";",
                "",
            ]
        )
    return "\n".join(sections).rstrip() + "\n"


def _prefix_build_context(
    registry: Registry,
    source_table: str,
    source_physical: str,
) -> Tuple[List[str], str, str, str, str]:
    if source_table == "daily_quote":
        ts_expr = "`ts_code`"
        date_expr = "`trade_date`"
        return (
            [
                ts_expr,
                date_expr,
                f"ROW_NUMBER() OVER (PARTITION BY {ts_expr} ORDER BY {date_expr}) AS `row_no`",
            ],
            f"FROM `{source_physical}`",
            ts_expr,
            date_expr,
            "",
        )

    skeleton_physical = registry.table("daily_quote")["physical"]
    ts_expr = "base.`ts_code`"
    date_expr = "base.`trade_date`"
    from_sql = (
        f"FROM `{skeleton_physical}` AS base\n"
        f"LEFT JOIN `{source_physical}` AS src "
        f"ON src.`ts_code` = {ts_expr} AND src.`trade_date` = {date_expr}"
    )
    return (
        [
            f"{ts_expr} AS `ts_code`",
            f"{date_expr} AS `trade_date`",
            f"ROW_NUMBER() OVER (PARTITION BY {ts_expr} ORDER BY {date_expr}) AS `row_no`",
        ],
        from_sql,
        ts_expr,
        date_expr,
        "src",
    )


def _render_smoke_queries(registry: Registry, database: str) -> str:
    compiler = Compiler(registry=registry)
    optimized = compiler.compile(SMOKE_DSL)
    baseline = compiler.compile(SMOKE_DSL, enable_prefix_sum=False)
    return "\n".join(
        [
            "-- Smoke queries generated from the same DSL with optimizer on/off.",
            f"USE `{database}`;",
            "",
            "-- Optimized prefix-sum SQL",
            optimized.sql + ";",
            "",
            "-- Baseline window SQL",
            baseline.sql + ";",
            "",
        ]
    )


def _base_columns(registry: Registry, table_name: str) -> List[Tuple[str, str]]:
    columns = [("ts_code", "VARCHAR(32) NOT NULL"), ("trade_date", "DATE NOT NULL")]
    if table_name == "stock_universe":
        columns.append(("market", "VARCHAR(16)"))
        return columns
    for indicator_name, meta in registry.indicators.items():
        if meta["table"] == table_name:
            columns.append((meta["column"], _indicator_type(indicator_name, meta)))
    return columns


def _prefix_columns(registry: Registry, prefix_table_name: str) -> List[Tuple[str, str]]:
    columns = [
        ("ts_code", "VARCHAR(32) NOT NULL"),
        ("trade_date", "DATE NOT NULL"),
        ("row_no", "BIGINT NOT NULL"),
    ]
    for indicator_name, meta in registry.indicators.items():
        if meta.get("prefix_table") == prefix_table_name:
            columns.append((meta["prefix_column"], _prefix_type(indicator_name)))
    return columns


def _indicator_type(indicator_name: str, meta: Dict[str, object]) -> str:
    if indicator_name == "volume":
        return "BIGINT"
    if meta.get("type") == "numeric":
        return "DOUBLE"
    return "VARCHAR(64)"


def _prefix_type(indicator_name: str) -> str:
    if indicator_name == "volume":
        return "BIGINT"
    return "DOUBLE"


def _prefix_table_names(registry: Registry) -> List[str]:
    names = []
    for meta in registry.indicators.values():
        prefix_table = meta.get("prefix_table")
        if meta.get("supports_prefix_sum") and prefix_table and prefix_table not in names:
            names.append(prefix_table)
    return names


def _prefix_source(registry: Registry, prefix_table_name: str):
    source_table = None
    indicators = []
    for indicator_name, meta in registry.indicators.items():
        if meta.get("prefix_table") == prefix_table_name:
            source_table = meta["table"]
            indicators.append((indicator_name, meta))
    if source_table is None:
        raise ValueError(f"No source table found for prefix table {prefix_table_name}")
    return source_table, indicators


def _read_csv(path: Path) -> List[Dict[str, str]]:
    with path.open("r", encoding="utf-8-sig", newline="") as fh:
        return list(csv.DictReader(fh))


def _insert_sql(table: str, columns: List[str], rows: Iterable[Dict[str, str]]) -> str:
    quoted_columns = ", ".join(f"`{column}`" for column in columns)
    values = []
    for row in rows:
        values.append("(" + ", ".join(_literal(row[column]) for column in columns) + ")")
    return f"INSERT INTO `{table}` ({quoted_columns}) VALUES\n" + ",\n".join(values) + ";"


def _literal(value: str) -> str:
    if value == "":
        return "NULL"
    try:
        float(value)
    except ValueError:
        return "'" + value.replace("'", "''") + "'"
    return value
